package ScratchPad;


public class ScratchTypes {
    public static void main(String[] args) {
        /*
         * ✅ Problem: Print all Java primitive data types with their min and max values
         * - Use: byte, short, int, long, float, double, char, boolean
         * - Use Wrapper classes like Byte.MIN_VALUE and Byte.MAX_VALUE
         * - Bonus: Declare variables and print their values too
         */
        System.out.println("Minimum Value: " + Byte.MIN_VALUE + " Maximum Value: " + Byte.MAX_VALUE);
        System.out.println("Minimum Value: " + Short.MIN_VALUE + " Maximum Value: " + Short.MAX_VALUE);
        System.out.println("Minimum Value: " + Integer.MIN_VALUE + " Maximum Value: " + Integer.MAX_VALUE);
        System.out.println("Minimum Value: " + Long.MIN_VALUE + " Maximum Value: " + Long.MAX_VALUE);
    }   
}
